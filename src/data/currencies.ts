export const CURRENCY_OPTIONS = CURRENCIES.map((c) => ({
  value: c.code,
  label: `${c.code} — ${c.name}`,
}));

export function currencyLabel(code: string): string {
  const hit = CURRENCIES.find((c) => c.code === code.toUpperCase());
  return hit ? `${hit.code} — ${hit.name}` : code;
}
